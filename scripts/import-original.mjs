import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createHash } from "node:crypto";
const directory = JSON.parse(
  readFileSync(".reference/extracted/directory.json", "utf8"),
);
const names = {
  3: "doors",
  6: "platforms",
  9: "poles",
  12: "ladders",
  15: "bells",
  18: "lightning",
  21: "fields",
  24: "mummies",
  27: "keys",
  30: "locks",
  33: "graphics",
  36: "guns",
  39: "teleporters",
  42: "traps",
  45: "conveyors",
  48: "creatures",
  51: "texts",
  54: "bitmap",
};
const sizes = {
  3: 8,
  6: 3,
  9: 3,
  12: 3,
  15: 3,
  18: 8,
  21: 4,
  24: 7,
  27: 4,
  30: 5,
  33: 6,
  36: 7,
  42: 5,
  45: 5,
  48: 7,
};
const castles = [];
for (const file of directory.filter((f) => f.name.startsWith("Z"))) {
  const data = readFileSync(`.reference/extracted/${file.file}`).subarray(2),
    name = file.name.slice(1).toLowerCase();
  const castle = {
    id: name,
    name: name[0].toUpperCase() + name.slice(1),
    sourceHash: file.sha256,
    startRoom: data[3],
    startDoor: data[5],
    player2: { room: data[4], door: data[6] },
    rooms: [],
  };
  for (let p = 256; data[p] !== 64 && data[p] !== 255; p += 8) {
    if (castle.rooms.length > 100) throw Error("Invalid room directory");
    const room = {
      id: castle.rooms.length,
      color: data[p] & 15,
      map: {
        x: data[p + 1],
        y: data[p + 2],
        width: (data[p + 3] >> 3) & 7,
        height: data[p + 3] & 7,
      },
      offset: data.readUInt16LE(p + 6) - 0x7800,
      objects: {},
    };
    let q = room.offset,
      guard = 0;
    while (data.readUInt16LE(q) !== 0) {
      if (++guard > 100)
        throw Error(`Too many object groups ${name}/${room.id}`);
      const address = data.readUInt16LE(q),
        type = address - 0x800;
      q += 2;
      if (!names[type])
        throw Error(
          `Unknown object ${address.toString(16)} at ${name}/${room.id}/${q.toString(16)}`,
        );
      const items = (room.objects[names[type]] ||= []);
      if (type === 3 || type === 15) {
        let count = data[q++];
        while (count--) {
          items.push([...data.subarray(q, q + sizes[type])]);
          q += sizes[type];
        }
      } else if (type === 39) {
        const booth = [...data.subarray(q, q + 3)];
        q += 3;
        const targets = [];
        while (data[q] !== 0) {
          targets.push([...data.subarray(q, q + 2)]);
          q += 2;
        }
        q++;
        items.push({ booth, targets });
      } else if (type === 51) {
        while (data[q] !== 0) {
          const header = [...data.subarray(q, q + 4)];
          q += 4;
          const chars = [];
          let c;
          do {
            c = data[q++];
            chars.push(c & 127);
          } while (!(c & 128));
          items.push({ header, text: String.fromCharCode(...chars) });
        }
        q++;
      } else if (type === 54) {
        throw Error("Unexpected bitmap in room");
      } else {
        const end =
          type === 18 ? 32 : [36, 42, 45, 48].includes(type) ? 128 : 0;
        while (data[q] !== end) {
          items.push([...data.subarray(q, q + sizes[type])]);
          q += sizes[type];
          if (q > data.length) throw Error("Unterminated object list");
        }
        q++;
      }
    }
    castle.rooms.push(room);
  }
  castles.push(castle);
}
mkdirSync("src/data", { recursive: true });
writeFileSync(
  "src/data/original-castles.json",
  JSON.stringify(castles, null, 2),
);
writeFileSync(
  "src/data/original-castles.js",
  "// Original C64 room records. Generated by scripts/import-original.mjs; see SOURCES.md.\nexport default " +
    JSON.stringify(castles) +
    ";\n",
);
console.log(
  castles.map((c) => ({
    name: c.name,
    rooms: c.rooms.length,
    start: [c.startRoom, c.startDoor],
    types: [...new Set(c.rooms.flatMap((r) => Object.keys(r.objects)))],
  })),
);
console.log(
  "Total rooms:",
  castles.reduce((n, c) => n + c.rooms.length, 0),
);
